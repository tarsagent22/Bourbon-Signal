#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULT_LIFECYCLE_JSON = path.join(ROOT, 'src', 'config', 'state-lifecycle.json');
export const DEFAULT_LIFECYCLE_TS = path.join(ROOT, 'src', 'config', 'stateLifecycle.ts');

export function renderStateLifecycleTypes(config) {
  return `// This file is generated by scripts/generate-state-lifecycle-types.mjs. Do not edit manually.\n\nexport const STATE_LIFECYCLE_CONFIG = ${JSON.stringify(config, null, 2)} as const;\n\nexport type StateLifecycleConfig = typeof STATE_LIFECYCLE_CONFIG;\nexport type ActiveStateCode = StateLifecycleConfig["activeStates"][number];\nexport type StateLifecycleEntry = StateLifecycleConfig["states"][keyof StateLifecycleConfig["states"]];\n`;
}

export async function verifyStateLifecycleDrift({ config, actual, configPath = DEFAULT_LIFECYCLE_JSON, outputPath = DEFAULT_LIFECYCLE_TS } = {}) {
  const resolvedConfig = config ?? JSON.parse(await readFile(configPath, 'utf8'));
  const resolvedActual = actual ?? await readFile(outputPath, 'utf8');
  const expected = renderStateLifecycleTypes(resolvedConfig);
  const normalizeNewlines = (value) => String(value).replaceAll(String.fromCharCode(13), '');
  const matches = normalizeNewlines(resolvedActual) === normalizeNewlines(expected);
  return {
    ok: matches,
    expected,
    actual: resolvedActual,
    reason: matches ? null : 'Generated src/config/stateLifecycle.ts has drifted from authoritative src/config/state-lifecycle.json. Run npm run generate:state-lifecycle-types.',
  };
}

export async function generateStateLifecycleTypes({ configPath = DEFAULT_LIFECYCLE_JSON, outputPath = DEFAULT_LIFECYCLE_TS } = {}) {
  const config = JSON.parse(await readFile(configPath, 'utf8'));
  const output = renderStateLifecycleTypes(config);
  await writeFile(outputPath, output, 'utf8');
  return { configPath, outputPath, output };
}

async function main() {
  const check = process.argv.includes('--check');
  if (check) {
    const result = await verifyStateLifecycleDrift();
    if (!result.ok) throw new Error(result.reason);
    console.log('State lifecycle generated TypeScript is in exact sync.');
    return;
  }
  const result = await generateStateLifecycleTypes();
  console.log(`Generated ${path.relative(ROOT, result.outputPath).replaceAll('\\', '/')}.`);
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : '';
if (import.meta.url === invokedPath) {
  main().catch((error) => { console.error(error.message); process.exit(1); });
}
